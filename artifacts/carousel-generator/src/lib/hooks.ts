// Splits a hook into a big headline and a subtitle that finishes the thought, keeping her words exactly.
export function splitHook(h: string): { headline: string; subtitle: string } {
  const m = h.match(/^(.{6,40}?[:.?!])\s+(.+)$/);
  if (m && m[1].split(/\s+/).length <= 7) return { headline: m[1].replace(/[:.]$/, ""), subtitle: m[2] };
  const w = h.split(/\s+/);
  if (w.length <= 5) return { headline: h, subtitle: "" };
  return { headline: w.slice(0, 4).join(" "), subtitle: w.slice(4).join(" ") };
}

// Picks a hook at random, never repeating one inside the same pack.
export function pickHook(used: Set<number>): string {
  let i = Math.floor(Math.random() * HOOKS.length);
  for (let t = 0; t < HOOKS.length && used.has(i); t++) i = (i + 1) % HOOKS.length;
  used.add(i);
  return HOOKS[i];
}
